import { useMemo } from 'react';

export function buildControlsPanelProps(options: Record<string, any>): Record<string, any> {
  return options;
}

export function useCheckoutControlsProps(options: Record<string, any>): Record<string, any> {
  const {
    selectedCustomer,
    setSelectedCustomer,
    customerSearch,
    setCustomerSearch,
    customers,
    isWholesale,
    setIsWholesale,
    useLoyaltyPoints,
    setUseLoyaltyPoints,
    settings,
    total,
    receivedAmount,
    setReceivedAmount,
    keepExcessInBalance,
    setKeepExcessInBalance,
    handleCheckout,
    addCustomerNote,
    setIsPOSCustomerModalOpen,
    deliveryMethod,
    setDeliveryMethod,
    voucherCode,
    setVoucherCode,
    appliedVoucher,
    setAppliedVoucher,
    applyVoucher,
    subtotal,
    discountAmount,
    pointsDiscount,
    voucherDiscount,
    currency,
    cart,
    isProcessing,
    setIsDeliveryModalOpen,
    globalDiscount,
    setGlobalDiscount,
    editingTransaction
  } = options;

  return useMemo(() => ({
    selectedCustomer,
    setSelectedCustomer,
    customerSearch,
    setCustomerSearch,
    customers,
    isWholesale,
    setIsWholesale,
    useLoyaltyPoints,
    setUseLoyaltyPoints,
    settings,
    total,
    receivedAmount,
    setReceivedAmount,
    keepExcessInBalance,
    setKeepExcessInBalance,
    handleCheckout,
    addCustomerNote,
    setIsPOSCustomerModalOpen,
    deliveryMethod,
    setDeliveryMethod,
    voucherCode,
    setVoucherCode,
    appliedVoucher,
    setAppliedVoucher,
    applyVoucher,
    subtotal,
    discountAmount,
    pointsDiscount,
    voucherDiscount,
    currency: currency || settings?.currency,
    cart,
    isProcessing,
    setIsDeliveryModalOpen,
    globalDiscount,
    setGlobalDiscount,
    editingTransaction
  }), [
    selectedCustomer, setSelectedCustomer, customerSearch, setCustomerSearch,
    customers, isWholesale, setIsWholesale, useLoyaltyPoints, setUseLoyaltyPoints,
    settings, total, receivedAmount, setReceivedAmount, keepExcessInBalance,
    setKeepExcessInBalance, handleCheckout, addCustomerNote, setIsPOSCustomerModalOpen,
    deliveryMethod, setDeliveryMethod, voucherCode, setVoucherCode, appliedVoucher,
    setAppliedVoucher, applyVoucher, subtotal, discountAmount, pointsDiscount,
    voucherDiscount, cart, isProcessing, setIsDeliveryModalOpen, globalDiscount,
    setGlobalDiscount, editingTransaction, currency
  ]);
}
